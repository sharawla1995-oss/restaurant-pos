 v_emp:=public.current_employee_id();
 insert into public.restaurant_table_session_orders(session_id,order_id,attached_by_employee_id)
 values(v_s.id,p_order_id,v_emp) on conflict(order_id) do nothing;
 if not exists(select 1 from public.restaurant_table_session_orders where session_id=v_s.id and order_id=p_order_id) then raise exception 'الطلب مرتبط بجلسة أخرى'; end if;
 insert into public.audit_logs(employee_id,branch_id,action,entity_type,entity_id,details)
 values(v_emp,v_s.branch_id,'restaurant.tables.use','restaurant_table_session',v_s.id,jsonb_build_object('order_id',p_order_id,'event','attach_order'));
 return v_s.id;
end;$$;

