create or replace function public.restaurant_table_session_attach_order_v1(p_session_id bigint,p_order_id bigint) returns bigint
language plpgsql security definer set search_path=public as $$
declare v_s public.restaurant_table_sessions%rowtype;v_order record;v_emp bigint;
begin
 if auth.uid() is null then raise exception 'غير مصرح'; end if;
 if not public.has_action_permission_v2('restaurant.tables.use') then raise exception 'ليس لديك صلاحية ربط الطلب بالترابيزة'; end if;
