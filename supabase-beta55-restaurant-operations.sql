 if not found or v_s.status<>'open' then raise exception 'جلسة الترابيزة غير مفتوحة'; end if;
 if not public.has_branch_access(v_s.branch_id) then raise exception 'ليس لديك صلاحية لهذا الفرع'; end if;
 select id,branch_id,order_type into v_order from public.orders where id=p_order_id;
 if not found then raise exception 'الطلب غير موجود'; end if;
