create or replace function public.food_apply_ingredient_delta_internal_v1(
 p_branch_id bigint,
 p_ingredient_id bigint,
 p_quantity_delta numeric,
 p_unit_cost numeric,
 p_movement_type text,
 p_reference_type text,
 p_reference_id bigint,
 p_notes text
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare
 v_stock public.ingredient_stock%rowtype;
 v_track boolean;
 v_new numeric(18,6);
 v_avg numeric(18,6);
 v_cost numeric(18,6):=greatest(0,coalesce(p_unit_cost,0));
begin
 if coalesce(p_quantity_delta,0)=0 then
   select * into v_stock from public.ingredient_stock where branch_id=p_branch_id and ingredient_id=p_ingredient_id;
   return jsonb_build_object('quantity',coalesce(v_stock.quantity,0),'average_unit_cost',coalesce(v_stock.average_unit_cost,0));
 end if;
 select track_inventory into v_track from public.ingredients where id=p_ingredient_id and active is distinct from false;
 if not found then raise exception 'الخامة غير موجودة أو موقوفة'; end if;
 if not coalesce(v_track,true) then raise exception 'الخامة غير متتبعة بالمخزون'; end if;
 insert into public.ingredient_stock(branch_id,ingredient_id,quantity) values(p_branch_id,p_ingredient_id,0)
 on conflict(branch_id,ingredient_id) do nothing;
 select * into v_stock from public.ingredient_stock where branch_id=p_branch_id and ingredient_id=p_ingredient_id for update;
 v_new:=round(v_stock.quantity+p_quantity_delta,6);
 if v_new<0 then raise exception 'مخزون الخامة غير كافٍ'; end if;
 v_avg:=v_stock.average_unit_cost;
 if p_quantity_delta>0 and v_cost>0 then
   v_avg:=case when v_new<=0 then v_cost else round(((v_stock.quantity*v_stock.average_unit_cost)+(p_quantity_delta*v_cost))/v_new,6) end;
 end if;
 update public.ingredient_stock
 set quantity=v_new,
     average_unit_cost=greatest(0,coalesce(v_avg,0)),
     last_purchase_cost=case when p_movement_type='purchase' and v_cost>0 then v_cost else last_purchase_cost end,
     last_costed_at=case when p_movement_type='purchase' and v_cost>0 then now() else last_costed_at end,
     updated_at=now()
 where id=v_stock.id;
 insert into public.stock_movements(branch_id,ingredient_id,movement_type,quantity,reference_type,reference_id,notes)
 values(p_branch_id,p_ingredient_id,p_movement_type,round(p_quantity_delta,6),p_reference_type,p_reference_id,p_notes);
 return jsonb_build_object('quantity',v_new,'average_unit_cost',greatest(0,coalesce(v_avg,0)));
end;$$;
revoke all on function public.food_apply_ingredient_delta_internal_v1(bigint,bigint,numeric,numeric,text,text,bigint,text) from public,authenticated;

