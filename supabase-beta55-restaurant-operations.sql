create or replace function public.food_purchase_order_create_v1(
 p_branch_id bigint,
 p_supplier_id bigint,
 p_invoice_number text,
 p_notes text,
 p_items jsonb,
 p_client_tx_id text
) returns bigint
language plpgsql security definer set search_path=public as $$
declare
 v_id bigint;v_emp bigint;v_key text:=nullif(trim(coalesce(p_client_tx_id,'')),'');v record;
 v_base text;v_unit text;v_factor numeric(18,6);v_qty numeric(18,6);v_cost numeric(18,6);v_total numeric(18,6):=0;
begin
 if auth.uid() is null then raise exception 'غير مصرح'; end if;
 if not public.has_action_permission_v2('food.purchasing.create') then raise exception 'ليس لديك صلاحية إنشاء أمر شراء خامات'; end if;
 if not public.has_branch_access(p_branch_id) then raise exception 'ليس لديك صلاحية لهذا الفرع'; end if;
 if v_key is null then raise exception 'معرف الحركة مطلوب'; end if;
 if not exists(select 1 from public.suppliers where id=p_supplier_id and active is distinct from false) then raise exception 'المورد غير موجود أو موقوف'; end if;
 if jsonb_array_length(coalesce(p_items,'[]'::jsonb))=0 then raise exception 'أضف خامة واحدة على الأقل'; end if;
 perform pg_advisory_xact_lock(hashtextextended('food-po:'||v_key,0));
 select id into v_id from public.purchases where client_tx_id=v_key;
 if v_id is not null then return v_id; end if;
 v_emp:=public.current_employee_id();
 insert into public.purchases(branch_id,supplier_id,invoice_number,total,paid,notes,status,client_tx_id,created_by_employee_id,updated_at)
 values(p_branch_id,p_supplier_id,nullif(trim(coalesce(p_invoice_number,'')),''),0,0,nullif(trim(coalesce(p_notes,'')),''),'draft',v_key,v_emp,now()) returning id into v_id;
 for v in select * from jsonb_to_recordset(p_items) as x(ingredient_id bigint,quantity numeric,unit_code text,unit_cost numeric) loop
   select coalesce(base_unit_code,unit),coalesce(purchase_unit_code,base_unit_code,unit) into v_base,v_unit from public.ingredients where id=v.ingredient_id and active is distinct from false;
   if not found then raise exception 'خامة غير صالحة %',v.ingredient_id; end if;
   v_qty:=round(coalesce(v.quantity,0)::numeric,6);v_cost:=round(coalesce(v.unit_cost,-1)::numeric,6);v_unit:=coalesce(nullif(trim(coalesce(v.unit_code,'')),''),v_unit,v_base);
   if v_qty<=0 or v_cost<0 then raise exception 'كمية/تكلفة غير صحيحة للخامة %',v.ingredient_id; end if;
   v_factor:=public.ingredient_unit_factor_v1(v.ingredient_id,v_unit,v_base);
   if v_factor is null or v_factor<=0 then raise exception 'لا يوجد تحويل وحدة صالح للخامة % من % إلى %',v.ingredient_id,v_unit,v_base; end if;
   insert into public.purchase_items(purchase_id,ingredient_id,quantity,unit_cost,total,unit_code,conversion_factor_to_base,received_quantity,base_quantity_ordered,base_quantity_received)
   values(v_id,v.ingredient_id,v_qty,v_cost,round(v_qty*v_cost,6),v_unit,v_factor,0,round(v_qty*v_factor,6),0);
   v_total:=v_total+round(v_qty*v_cost,6);
 end loop;
 update public.purchases set total=round(v_total,6),updated_at=now() where id=v_id;
 insert into public.audit_logs(employee_id,branch_id,action,entity_type,entity_id,details)
 values(v_emp,p_branch_id,'food.purchasing.create','purchase',v_id,jsonb_build_object('supplier_id',p_supplier_id,'client_tx_id',v_key,'total',round(v_total,6)));
 return v_id;
end;$$;

create or replace function public.food_purchase_order_approve_v1(p_purchase_id bigint) returns bigint
language plpgsql security definer set search_path=public as $$
declare v_po public.purchases%rowtype;v_emp bigint;
begin
 if auth.uid() is null then raise exception 'غير مصرح'; end if;
 if not public.has_action_permission_v2('food.purchasing.approve') then raise exception 'ليس لديك صلاحية اعتماد أمر شراء خامات'; end if;
 select * into v_po from public.purchases where id=p_purchase_id for update;
 if not found then raise exception 'أمر الشراء غير موجود'; end if;
 if not public.has_branch_access(v_po.branch_id) then raise exception 'ليس لديك صلاحية لهذا الفرع'; end if;
 if v_po.status='approved' then return v_po.id; end if;
 if v_po.status<>'draft' then raise exception 'يمكن اعتماد المسودة فقط'; end if;
 v_emp:=public.current_employee_id();
 update public.purchases set status='approved',approved_by_employee_id=v_emp,approved_at=now(),updated_at=now() where id=v_po.id;
 insert into public.audit_logs(employee_id,branch_id,action,entity_type,entity_id,details)
 values(v_emp,v_po.branch_id,'food.purchasing.approve','purchase',v_po.id,null);
 return v_po.id;
end;$$;

