import {createClient} from 'https://esm.sh/@supabase/supabase-js@2.58.0';
import {createTopChickenStaffHandler} from './core.mjs';
import {cloudExecutor,signedAuthorityReader} from './cloud-authority.mjs';
const url=Deno.env.get('SUPABASE_URL')||'';
const service=Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')||'';
const anon=Deno.env.get('SUPABASE_ANON_KEY')||'';
if(url!=='https://xihcxydjnzemflhedzor.supabase.co'||!service||!anon)throw new Error('Top Chicken Beta project required');
const options={auth:{persistSession:false,autoRefreshToken:false}};
const secret=Deno.env.get('TC_CLOUD_AUTHORITY_SECRET')||'',publicKey=Deno.env.get('TC_CLOUD_PUBLIC_KEY')||'';
const admin=createClient(url,service,options);
const executeRPC=cloudExecutor({readSnapshot:signedAuthorityReader({publicKey,secret}),beta:admin});
Deno.serve(createTopChickenStaffHandler({admin,executeRPC,authClient:createClient(url,anon,options),digestSecret:service}));
