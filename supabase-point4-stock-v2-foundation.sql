-- A reversal is a new, exact inverse of one original movement. It cannot change
-- the stock identity or reverse another reversal.
create or replace function public.inventory_stock_reversal_validate_v2()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_original public.inventory_stock_movements_v2%rowtype;
begin
  if new.reversal_of_movement_id is null then
    return new;
  end if;

  select * into v_original
  from public.inventory_stock_movements_v2 m
  where m.id=new.reversal_of_movement_id
  for update;
  if not found then
    raise exception 'INVENTORY_STOCK_V2_REVERSAL_SOURCE_NOT_FOUND';
  end if;
  if v_original.movement_type='reversal' or v_original.reversal_of_movement_id is not null then
    raise exception 'INVENTORY_STOCK_V2_REVERSAL_OF_REVERSAL';
  end if;
  if new.location_id<>v_original.location_id
    or new.item_kind<>v_original.item_kind
    or new.item_id<>v_original.item_id then
    raise exception 'INVENTORY_STOCK_V2_REVERSAL_IDENTITY_MISMATCH';
  end if;
  if new.quantity_delta<>-v_original.quantity_delta then
    raise exception 'INVENTORY_STOCK_V2_REVERSAL_QUANTITY_MISMATCH';
  end if;
  if new.reserved_quantity_delta<>-v_original.reserved_quantity_delta then
    raise exception 'INVENTORY_STOCK_V2_REVERSAL_RESERVATION_MISMATCH';
  end if;
  if (new.value_delta is null)<>(v_original.value_delta is null)
    or (
      new.value_delta is not null
      and v_original.value_delta is not null
      and new.value_delta<>-v_original.value_delta
    ) then
    raise exception 'INVENTORY_STOCK_V2_REVERSAL_VALUE_MISMATCH';
  end if;

  return new;
end;
$$;

drop trigger if exists inventory_stock_movements_v2_reversal_validate
  on public.inventory_stock_movements_v2;
create trigger inventory_stock_movements_v2_reversal_validate
before insert
on public.inventory_stock_movements_v2
for each row execute function public.inventory_stock_reversal_validate_v2();

-- -----------------------------------------------------------------------------
-- 4) Future-writer contracts. These functions are intentionally internal only.
--    No current application path is granted execution or routed through them.
-- -----------------------------------------------------------------------------
create or replace function public.inventory_stock_resolve_policy_v2(
  p_location_id bigint,
  p_item_kind text,
  p_item_id bigint
) returns table(
  allow_negative_stock boolean,
  policy_code text,
  policy_version integer,
  policy_source text
)
language plpgsql
stable
security invoker
set search_path=public
as $$
begin
  if not exists(select 1 from public.branches where id=p_location_id) then
    raise exception 'INVENTORY_STOCK_V2_LOCATION_REQUIRED';
  end if;
  if p_item_kind is null or p_item_kind not in ('product','variant','ingredient') or coalesce(p_item_id,0)<=0 then
    raise exception 'INVENTORY_STOCK_V2_ITEM_REQUIRED';
  end if;

  return query
  select b.allow_negative_stock,b.policy_code,b.policy_version,'balance'::text
  from public.inventory_stock_balances_v2 b
  where b.location_id=p_location_id
    and b.item_kind=p_item_kind
    and b.item_id=p_item_id;

  if not found then
    return query select false,'fail_closed'::text,1,'default_fail_closed'::text;
  end if;
end;
$$;

create or replace function public.inventory_stock_resolve_idempotency_v2(
  p_client_tx_id text,
  p_line_key text,
  p_operation_digest text
) returns table(
  movement_id bigint,
  reuse_existing boolean
)
language plpgsql
security invoker
set search_path=public
as $$
declare
  v_existing public.inventory_stock_movements_v2%rowtype;
  v_client_tx_id text:=trim(coalesce(p_client_tx_id,''));
  v_line_key text:=trim(coalesce(p_line_key,''));
  v_digest text:=lower(trim(coalesce(p_operation_digest,'')));
begin
  if v_client_tx_id='' or v_line_key='' or v_digest !~ '^[0-9a-f]{64}$' then
    raise exception 'INVENTORY_STOCK_V2_IDEMPOTENCY_KEY_REQUIRED';
  end if;

  -- The future canonical writer calls this inside its transaction. The lock
  -- serializes a key through the following insert, while the unique constraint
  -- remains the final database-level duplicate guard.
  perform pg_advisory_xact_lock(
    hashtextextended('inventory-stock-v2:'||v_client_tx_id||':'||v_line_key,0)
  );

  select * into v_existing
  from public.inventory_stock_movements_v2 m
  where m.client_tx_id=v_client_tx_id and m.line_key=v_line_key;

  if not found then
    return query select null::bigint,false;
    return;
  end if;

  if v_existing.operation_digest<>v_digest then
    raise exception 'INVENTORY_STOCK_V2_IDEMPOTENCY_CONFLICT';
  end if;

  return query select v_existing.id,true;
end;
$$;

