'use strict';
const fs=require('fs');
const transport=fs.readFileSync('beta45-offline-v2-transport-runtime.js','utf8');
const inbox=fs.readFileSync('beta45-offline-v2-inbox-runtime.js','utf8');
const pkg=require('../package.json');
const must=(x,m)=>{if(!x)throw new Error(m)};
must(pkg.version==='10.5.4-beta.58.32','hotfix version mismatch');
must(transport.includes("timer=setInterval(()=>{if(navigator.onLine)syncNow().catch(()=>{})},60_000);"),'transport fallback poll must be 60s');
must(inbox.includes("timer=setInterval(()=>{if(navigator.onLine)pullNow().catch(()=>{})},60_000);"),'inbox fallback poll must be 60s');
must(transport.includes("setTimeout(()=>{syncNow().catch(()=>{})},0);"),'local-first commit must schedule sync asynchronously');
must(!transport.includes("if(row?.status!=='synced')try{await syncNow()}catch(e){/* durable row below remains authoritative */}"),'local-first commit must not block UI on sync');
const recStart=transport.indexOf('async function reconcileCompatibilityProjections(){');
const recEnd=transport.indexOf('async function reconcileOrderStatusProjection(){',recStart);
must(recStart>=0&&recEnd>recStart,'reconciliation block missing');
const rec=transport.slice(recStart,recEnd);
const getKeys=[...rec.matchAll(/global\.odbGet\('([^']+)'\)/g)].map(x=>x[1]);
const setKeys=[...rec.matchAll(/global\.odbSet\('([^']+)'/g)].map(x=>x[1]);
must(new Set(getKeys).size===getKeys.length,'reconciliation must read each projection cache at most once');
must(new Set(setKeys).size===setKeys.length,'reconciliation must write each projection cache at most once');
must(!/for\s*\([^)]*\)\s*\{[^}]*odbGet\(/s.test(rec),'reconciliation must not perform cache reads inside row loop');
must(rec.includes("Promise.all(writes)"),'reconciliation writes must be coalesced');
console.log('RC1 offline performance hotfix gate PASS');
