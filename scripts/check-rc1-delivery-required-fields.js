'use strict';
const fs=require('fs');
const app=fs.readFileSync('app.js','utf8');
const must=(cond,msg)=>{if(!cond)throw new Error(msg)};
const start=app.indexOf('function validatedDeliveryCheckoutInput(){');
const end=start>=0?app.indexOf('async function checkout(payment,payments=null){',start):-1;
must(start>=0&&end>start,'RC1 delivery validation helper missing');
const helper=app.slice(start,end);
must(helper.includes("/^01[0125][0-9]{8}$/"),'delivery phone must use the server-compatible Egyptian mobile contract');
must(helper.includes("if(!address)throw new Error('عنوان التوصيل مطلوب لأوردر الدليفري')"),'delivery address must be required');
must(helper.includes("Number($('#deliveryZone')?.value||0)"),'delivery zone id must be read explicitly');
must(helper.includes("String(z.branch_id)===String(currentBranchId())"),'delivery zone must belong to the active branch');
const checkoutStart=app.indexOf('async function checkout(payment,payments=null){');
const checkoutEnd=app.indexOf('async function openMixedPayment()',checkoutStart);
must(checkoutStart>=0&&checkoutEnd>checkoutStart,'checkout function boundary missing');
const checkout=app.slice(checkoutStart,checkoutEnd);
const validateAt=checkout.indexOf("const deliveryInput=orderType==='delivery'?validatedDeliveryCheckoutInput():null;");
const customerAt=checkout.indexOf('customerRouter.createCustomer');
const localCommitAt=checkout.indexOf('saveOfflineSale(');
must(validateAt>=0,'checkout must invoke delivery validation');
must(customerAt>validateAt,'delivery validation must run before customer creation');
must(localCommitAt>validateAt,'delivery validation must run before any local sale commit');
must(checkout.includes("delivery_address:deliveryInput?.address||null"),'order payload must reuse the validated delivery address');
must(checkout.includes("delivery_zone_id:deliveryInput?.zoneId||null"),'order payload must reuse the validated delivery zone');
must(checkout.includes("const phone=deliveryInput?.phone||"),'order/customer payload must reuse the normalized validated delivery phone');
console.log('RC1 delivery required-fields gate PASS');
