const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const must=(cond,msg)=>{if(!cond)throw new Error(`Beta32 Capability gate failed: ${msg}`)};
const source=read('sharawla-capabilities.js');
const sandbox={window:{}};
sandbox.window.window=sandbox.window;
vm.runInNewContext(source,sandbox,{filename:'sharawla-capabilities.js'});
const api=sandbox.window.SharawlaCapabilities;
must(api,'Capability registry missing');
must(api.VERSION==='10.5.4-beta.32','Capability registry version mismatch');
must(api.FEATURE_COUNT>=60,`Expected >=60 features, got ${api.FEATURE_COUNT}`);
for(const p of ['restaurant','retail','pharmacy','logistics','membership','warehouse'])must(api.getProfile(p),`Missing profile ${p}`);
for(const p of ['restaurant','retail','pharmacy'])must(api.getProfile(p).implemented===true,`${p} must remain implemented`);
for(const p of ['logistics','membership','warehouse'])must(api.getProfile(p).implemented===false,`${p} must remain planned in foundation`);
const pharmacy=api.resolveRuntime({pos_profile:'pharmacy',modules_configured:true,enabled_modules:['pos','customers','inventory','returns','reports','expenses','barcode','delivery','pickup','website','promocodes','pharmacy','insurance']});
for(const f of ['commerce.pos','inventory.stock','inventory.batch','inventory.expiry','pharmacy.catalog','pharmacy.prescriptions','pharmacy.insurance','pharmacy.claims'])must(pharmacy.features.includes(f),`Pharmacy legacy bridge missing ${f}`);
const logistics=api.getProfile('logistics');
for(const f of ['logistics.shipments','logistics.tracking','logistics.cod','logistics.client_settlements'])must(logistics.features.includes(f),`Logistics preset missing ${f}`);
const gym=api.getProfile('membership');
for(const f of ['membership.members','membership.subscriptions','membership.checkin','membership.bookings','membership.freeze'])must(gym.features.includes(f),`Membership preset missing ${f}`);
const bad=api.validateSelection(['pharmacy.claims']);
must(bad.ok===false&&bad.missing.length>0,'Dependency validation must reject incomplete selection');
const closed=api.dependencyClosure(['pharmacy.claims']);
for(const f of ['pharmacy.claims','pharmacy.insurance','commerce.orders','commerce.pos','core.payments'])must(closed.includes(f),`Dependency closure missing ${f}`);
console.log(`Beta32 Capability registry gate OK: features=${api.FEATURE_COUNT}; profiles=${api.PROFILE_COUNT}`);
