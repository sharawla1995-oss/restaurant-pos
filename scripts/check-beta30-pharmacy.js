const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const must=(cond,msg)=>{if(!cond)throw new Error(`Beta30 Pharmacy gate failed: ${msg}`)};
const engine=read('pharmacy-engine.js');
const ui=read('pharmacy-ui.js');
const index=read('index.html');
const pkg=JSON.parse(read('package.json'));
const sw=read('sw.js');
const syntax=read('scripts/check-runtime-syntax.js');
const version=String(pkg.version||'');
const m=version.match(/^10\.5\.4-beta\.(\d+)$/);
must(m&&Number(m[1])>=30,'package version must be beta30 or newer');
must(engine.includes("code:'pharmacy'")&&engine.includes('pharmacyCatalog')&&engine.includes('pharmacyInsurance'),'Pharmacy engine incomplete');
must(ui.includes('create_pharmacy_pos_order_atomic')&&ui.includes('pharmacy_receive_batch')&&ui.includes('pharmacy_update_claim_status'),'Pharmacy operational workflows missing');
must(ui.includes('FEFO')||ui.includes('expiry_date'),'FEFO/expiry flow missing');
must(index.includes(`pharmacy-engine.js?v=${version}`)&&index.includes(`pharmacy-ui.js?v=${version}`),'Pharmacy assets not loaded');
must(sw.includes(`pharmacy-engine.js?v=${version}`)&&sw.includes(`pharmacy-ui.js?v=${version}`),'Pharmacy assets not cached');
must(syntax.includes("'pharmacy-engine.js'")&&syntax.includes("'pharmacy-ui.js'"),'Runtime syntax gate missing Pharmacy assets');
console.log(`Beta30+ Pharmacy static gate OK on ${version}`);
