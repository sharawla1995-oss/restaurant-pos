// Verifies the packaged candidate itself, not merely the source checkout.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const asar=require('asar');
const root='dist-top-chicken-connected-qa';
const cfg=JSON.parse(fs.readFileSync('top-chicken-connected-qa-build.json','utf8'));
assert.equal(cfg.appId,'com.sharawla.topchicken.qa.connected20261014');
assert.equal(cfg.productName,'Top Chicken Connected QA');
assert.equal(cfg.extraMetadata.topChickenPrelaunch,false);
assert.equal(cfg.extraMetadata.topChickenConnectedQa,true);
assert.equal(cfg.nsis.createDesktopShortcut,false);
assert.equal(cfg.nsis.createStartMenuShortcut,false);
const archive=path.join(root,'win-unpacked','resources','app.asar');
const pkg=JSON.parse(asar.extractFile(archive,'package.json').toString());
assert.equal(pkg.version,'10.5.4-beta.18');
assert.equal(pkg.topChickenConnectedQa,true);
assert.equal(pkg.topChickenPrelaunch,false);
const files=['main.js','app.js','preload.js','version.json','index.html','sw.js','update-config.json'];
for(const name of files)assert.deepEqual(asar.extractFile(archive,name),fs.readFileSync(name),name+' packaged bytes should equal source');
const main=asar.extractFile(archive,'main.js').toString();
assert.match(main,/function configureTopChickenQaNetwork\(\)/);
for(const host of ['xihcxydjnzemflhedzor.supabase.co','ikppryeavoabnugcijeq.supabase.co'])assert.ok(main.includes(host));
assert.ok(main.includes("url.protocol==='https:'"));
assert.ok(main.includes("return callback({cancel:false})"));
assert.ok(main.includes("callback({cancel:true})"));
assert.ok(main.includes("if(TOP_CHICKEN_PRELAUNCH||TOP_CHICKEN_CONNECTED_QA)return {enabled:false,channel:'beta'};"));
assert.ok(main.includes("'qa-backups'"));
const app=asar.extractFile(archive,'app.js').toString();
for(const feature of ['top-chicken-operations','top-chicken-staff','top_chicken_assign_order_driver','top_chicken_transition_order_status'])assert.ok(app.includes(feature),feature);
const release=fs.readdirSync(root).filter(n=>/\.exe$/i.test(n));
assert.equal(release.length,1);
const installer=release[0];
assert.match(installer,/^Top-Chicken-Connected-QA-10\.5\.4-beta\.18\.exe$/);
assert.deepEqual(cfg.win.target[0].arch,['x64'],'only x64 Windows installer may be built');
const bytes=fs.readFileSync(path.join(root,installer));
const result={result:'PASS',source_sha:process.env.GITHUB_SHA,installer,bytes:bytes.byteLength,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),features:'Beta/Cloud allowlist only, separate appId/userData/backups, updater disabled',online_e2e:'NOT EXECUTED',device_install:'NOT EXECUTED'};
fs.mkdirSync('evidence/top-chicken',{recursive:true});
fs.writeFileSync('evidence/top-chicken/connected-qa-package-check.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
