'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const tc=require('../../top-chicken-update-channel');
const business=tc.TC_BUSINESS,device=tc.TC_DEVICE;
const fingerprint='a'.repeat(64);
const good={device_id:device,business_id:business,device_fingerprint:fingerprint};
assert.equal(tc.identify(good,[fingerprint]),true);
assert.equal(tc.identify({...good,device_id:'00000000-0000-0000-0000-000000000000'},[fingerprint]),false);
assert.equal(tc.identify({...good,business_id:'00000000-0000-0000-0000-000000000000'},[fingerprint]),false);
assert.equal(tc.identify({...good,device_fingerprint:'b'.repeat(64)},[fingerprint]),false);
assert.equal(tc.identify(null,[fingerprint]),false);
assert.equal(tc.verifyResponse([{ok:true,business_id:business}]),true);
assert.equal(tc.verifyResponse([{ok:true,business_id:'00000000-0000-0000-0000-000000000000'}]),false);
assert.equal(tc.verifyResponse([{ok:false,business_id:business}]),false);
assert.equal(tc.verifyResponse([]),false);
assert.equal(tc.newer('10.5.19-rc.4','10.5.19-rc.3'),true);
assert.equal(tc.newer('10.5.19-rc.1','10.5.19-rc.3'),false);
assert.equal(tc.newer('10.5.19','10.5.19-rc.3'),true);
assert.equal(tc.newer('10.5.18','10.5.19-rc.3'),false);
assert.equal(tc.newer('10.5.20-rc.1','10.5.19-rc.3'),true);
assert.equal(tc.newer('broken','10.5.19-rc.3'),false);
const item={url:'https://github.com/sharawla1995-oss/restaurant-pos/releases/download/top-chicken-sh0008-v10.5.19-rc.4/Top-Chicken-SH0008-Primary-10.5.19-rc.4.exe',sha256:'b'.repeat(64)};
const feed={schema:1,channel:tc.TC_CHANNEL,device_id:device,business_id:business,enabled:true,version:'10.5.19-rc.4',assets:{x64:item}};
assert.equal(tc.choose(feed,'10.5.19-rc.3','x64').available,true);
assert.equal(tc.choose(feed,'10.5.19-rc.4','x64').available,false);
assert.equal(tc.choose(feed,'10.5.19-rc.3','ia32').available,false);
assert.equal(tc.choose({...feed,device_id:'other'},'10.5.19-rc.3','x64').available,false);
assert.equal(tc.choose({...feed,business_id:'other'},'10.5.19-rc.3','x64').available,false);
assert.equal(tc.choose({...feed,channel:'stable'},'10.5.19-rc.3','x64').available,false);
assert.equal(tc.choose({...feed,enabled:false},'10.5.19-rc.3','x64').available,false);
assert.equal(tc.choose({...feed,assets:{x64:{...item,sha256:'bad'}}},'10.5.19-rc.3','x64').available,false);
assert.equal(tc.choose({...feed,assets:{x64:{...item,url:'https://evil.example/exe'}}},'10.5.19-rc.3','x64').available,false);
assert.equal(tc.choose({...feed,assets:{x64:{...item,url:'https://github.com/sharawla1995-oss/restaurant-pos/releases/download/v10.5.19/Sharawla-POS-Setup-10.5.19-x64.exe'}}},'10.5.19-rc.3','x64').available,false);
const config=JSON.parse(fs.readFileSync('update-config.json','utf8'));
assert.equal(config.enabled,true);
assert.equal(config.channel,tc.TC_CHANNEL);
const bootstrap=JSON.parse(fs.readFileSync('top-chicken-updates/sh0008.json','utf8'));
assert.equal(bootstrap.version,'10.5.19-rc.3');
assert.equal(tc.choose(bootstrap,'10.5.19-rc.3','x64').available,false);
const main=fs.readFileSync('main.js','utf8');
assert.ok(main.includes('if(cfg.channel===topChickenUpdates.TC_CHANNEL)return checkForTopChickenUpdate({interactive});'));
assert.ok(main.includes("'/rest/v1/rpc/verify_sharawla_device'"));
assert.ok(main.includes("if(!topChickenUpdates.identify(st,deviceFingerprintCandidates()))"));
assert.ok(main.includes("if(!topChickenUpdates.verifyResponse(verification))"));
assert.ok(main.includes("if(!topChickenUpdates.verifyResponse(recheck))"));
assert.ok(main.includes("const manifest=await githubJson(topChickenUpdates.FEED_URL)"));
assert.ok(main.includes("const offer=topChickenUpdates.choose(manifest,app.getVersion(),arch)"));
assert.ok(main.includes('sha256File(target)!==offer.sha256'));
assert.ok(main.includes('createPreUpdateBackup(offer.version)'));
assert.ok(main.includes("pendingLocalOperationCount()>0"));
assert.ok(main.includes('/releases/latest')); // legacy retained only for ordinary, non-TC installs
assert.ok(tc.FEED_URL.includes('top-chicken-updates/sh0008.json'));
console.log('PASS targeted SH-0008-only update selector; foreign business/device blocked; cloud license gate; no generic latest for TC; local backup and SHA controls');
