do $$ declare r record; mid bigint; begin
 for r in select * from _tb_mods loop
   select id into mid from public.modifiers where name=r.name order by id limit 1;
   if mid is null then insert into public.modifiers(name,price,active) values(r.name,r.price,true); else update public.modifiers set price=r.price,active=true where id=mid; end if;
 end loop;
end $$;

