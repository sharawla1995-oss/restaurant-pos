   end if;
 end loop;
end $$;

-- Helper used only by this migration
create or replace function public._tb_menu_product(p_cat text,p_name text,p_price numeric,p_sort int default 0)
returns bigint language plpgsql as $$
declare cid bigint; pid bigint;
begin
 select id into cid from public.categories where name=p_cat order by id limit 1;
 select id into pid from public.products where name=p_name order by id limit 1;
 if pid is null then
   insert into public.products(name,category_id,price,cost,active,website_visible,website_sort_order,allow_extras,allow_removals,allow_item_notes)
   values(p_name,cid,p_price,0,true,true,p_sort,true,true,true) returning id into pid;
 else
   update public.products set category_id=cid,price=p_price,active=true,website_visible=true,website_sort_order=p_sort where id=pid;
 end if;
 insert into public.branch_products(branch_id,product_id,active) select b.id,pid,true from public.branches b where b.id in (1,2)
 on conflict(branch_id,product_id) do update set active=true;
 return pid;
end $$;

