create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  name text not null,
  price numeric(12,2) not null default 0,
  sort_order integer not null default 0,
  active boolean not null default true,
  unique(product_id,name)
);
alter table public.product_variants enable row level security;
grant select,insert,update,delete on public.product_variants to authenticated;
grant select on public.product_variants to anon;
drop policy if exists product_variants_staff_read on public.product_variants;
create policy product_variants_staff_read on public.product_variants for select to authenticated using (true);
drop policy if exists product_variants_staff_write on public.product_variants;
create policy product_variants_staff_write on public.product_variants for all to authenticated
using (public.has_permission('products')) with check (public.has_permission('products'));
drop policy if exists website_public_product_variants_read on public.product_variants;
create policy website_public_product_variants_read on public.product_variants for select to anon using (active=true);

